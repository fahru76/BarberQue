CREATE OR REPLACE FUNCTION public.book_appointment(p_name text, p_phone text, p_claim_token uuid, p_service text, p_duration_minutes integer, p_price_sen integer, p_date date, p_time time without time zone, p_service_ids text[] DEFAULT NULL::text[])
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_start  integer;
    v_end    integer;
    v_prefix text;
    v_id     text;
    v_computed_price_sen        integer;
    v_computed_duration_minutes integer;
begin
    perform public._expire_stale_waiting();  -- 20261012180000
    perform pg_advisory_xact_lock(hashtext('appointments:' || p_date::text));

    if p_claim_token is null then
        raise exception 'Missing claim token' using errcode = '22023';
    end if;

    -- Price/duration are recomputed from the live services catalog rather
    -- than trusted from the caller -- see migration header.
    if p_service_ids is null or array_length(p_service_ids, 1) is null then
        raise exception 'Sila pilih sekurang-kurangnya satu servis yang sah.' using errcode = '23514';
    end if;
    select coalesce(sum(price_sen), 0), coalesce(sum(duration_minutes), 0)
      into v_computed_price_sen, v_computed_duration_minutes
      from public.services
     where id = any(p_service_ids) and active;
    if v_computed_price_sen = 0 and v_computed_duration_minutes = 0 then
        raise exception 'Servis yang dipilih tidak sah atau tidak aktif.' using errcode = '23514';
    end if;
    p_price_sen := v_computed_price_sen;
    p_duration_minutes := v_computed_duration_minutes;

    if p_duration_minutes is null or p_duration_minutes <= 0 or p_duration_minutes > 480 then
        raise exception 'Invalid duration' using errcode = '22023';
    end if;
    v_start := extract(hour from p_time)::integer * 60 + extract(minute from p_time)::integer;
    v_end   := v_start + p_duration_minutes;

    if not public._appointment_hours_ok(p_date, v_start, v_end) then
        raise exception 'Slot ini di luar waktu operasi atau bertindih waktu rehat' using errcode = '22023';
    end if;
    if not public._appointment_slot_capacity_ok(p_date, v_start, v_end, null) then
        raise exception 'Slot ini tidak lagi tersedia' using errcode = '22023';
    end if;

    v_prefix := case when extract(hour from p_time) < 12 then 'PGB' else 'PTGB' end;
    v_id := public.next_ticket_number(v_prefix);

    insert into public.appointments (id, name, phone, claim_token, service, duration_minutes,
                                      price_sen, appt_date, appt_time, status, version, service_ids)
    values (v_id, p_name, p_phone, p_claim_token, p_service, p_duration_minutes,
            p_price_sen, p_date, p_time, 'upcoming', 1, p_service_ids);

    return v_id;
end $function$;

-- call_next_customer: unchanged except the PERFORM line marked 20261012180000
CREATE OR REPLACE FUNCTION public.call_next_customer(p_seat_no integer)
 RETURNS queues
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_barber             uuid := auth.uid();
    v_seat_barber        uuid;
    v_capability         text[];
    v_specialty          text[];
    v_service_durations  jsonb;
    v_covered            boolean;
    v_effective_duration integer;
    v_row                public.queues;
begin
    perform public._expire_stale_waiting();  -- 20261012180000
    if not public.is_active_staff() then
        raise exception 'Not authorised' using errcode = '42501';
    end if;

    select barber_id into v_seat_barber
      from public.seats
     where seat_no = p_seat_no and active;

    if v_seat_barber is null then
        raise exception 'Kerusi % tidak dibuka', p_seat_no using errcode = '22023';
    end if;

    -- Barber self duty (20261008100000): duty is per business day.
    if exists (select 1 from public.seats
                where seat_no = p_seat_no
                  and duty_date < public._current_business_date()) then
        raise exception 'Tugasan di kerusi % sudah tamat (hari perniagaan baharu). Sila Mula Bertugas semula.', p_seat_no using errcode = '22023';
    end if;

    if v_seat_barber <> v_barber and not public.is_admin() then
        raise exception 'Anda tidak ditugaskan pada kerusi ini' using errcode = '42501';
    end if;

    if exists (select 1 from public.queues where seat_no = p_seat_no and status = 'serving') then
        raise exception 'Kerusi % masih melayan pelanggan', p_seat_no using errcode = '22023';
    end if;

    select service_durations into v_service_durations from public.staff where id=v_seat_barber;
    select * into v_row from public.queues where status='waiting'
    order by (case when is_fast_pass then 0 when source='booking' then 1 else 2 end),created_at
    limit 1 for update skip locked;
    if v_row.id is null then
        raise exception 'Tiada pelanggan menunggu untuk servis yang anda boleh buat' using errcode = 'P0002';
    end if;

    -- Barber-specific duration override: only applied when this barber has
    -- an explicit, well-formed (1-999 minute) override for EVERY service on
    -- the ticket. Any gap, malformed value, or unknown service_ids falls
    -- back to the ticket's original duration_minutes untouched -- fail-safe
    -- by construction, so a bad/missing override can never break calling a
    -- customer in. (Unchanged from 20260908130000.)
    v_effective_duration := null;
    if v_row.service_ids is not null and array_length(v_row.service_ids, 1) > 0
       and v_service_durations is not null then
        select bool_and(
                 v_service_durations ? svc_id
                 and (v_service_durations ->> svc_id) ~ '^[1-9][0-9]{0,2}$'
               )
          into v_covered
          from unnest(v_row.service_ids) as svc_id;

        if coalesce(v_covered, false) then
            select sum((v_service_durations ->> svc_id)::integer)
              into v_effective_duration
              from unnest(v_row.service_ids) as svc_id;
        end if;
    end if;

    update public.queues
       set status           = 'serving',
           seat_no          = p_seat_no,
           barber_id        = coalesce(v_seat_barber, v_barber),
           called_at        = now(),
           duration_minutes = case
                                 when v_effective_duration between 1 and 480 then v_effective_duration
                                 else duration_minutes
                               end
     where id = v_row.id
    returning * into v_row;

    -- Barber break (20261008090000): calling a customer ends any break.
    update public.seats set break_until = null
     where seat_no = p_seat_no and break_until is not null;

    return v_row;
end $function$;

