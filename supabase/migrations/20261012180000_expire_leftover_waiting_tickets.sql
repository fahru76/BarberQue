-- Expire waiting tickets left over from an earlier business day.
--
-- Re-check 2026-10-13 (claude/logic-audit-2026-10-12.md): a ticket left
-- `waiting` when a business day ended (customer never served, never
-- cancelled) is invisible on every screen -- list_today_queues() only returns
-- today -- yet:
--   * take_walkin_ticket() counted it against shop_settings.max_queue, so the
--     first customer of the next day could get "Giliran penuh";
--   * call_next_customer() called it ahead of today's customers (it has the
--     oldest created_at);
--   * the booking capacity sweep counted it as live walk-in occupancy.
--
-- Fix: _expire_stale_waiting() cancels every `waiting` ticket created before
-- the current business day began (business-day aware, so an overnight
-- shift's pre-midnight tickets stay live), with a clear reason. It runs at
-- the start of every function that counts or calls waiting tickets. The six
-- bodies below are otherwise identical to their previous definitions
-- (20261012151733 / 20261009130000 / 20260919172934 lineage) -- generated by
-- inserting one PERFORM line, so grants are unchanged.
--
-- `serving` tickets are deliberately NOT expired: a customer may genuinely be
-- in the chair across the boundary; the barber finishes him with "Selesai".

create or replace function public._expire_stale_waiting()
returns void language plpgsql security definer set search_path = public as $$
begin
    update public.queues
       set status        = 'cancelled',
           cancelled_at  = now(),
           cancel_reason = 'Tamat hari perniagaan (tidak dilayan)'
     where status = 'waiting'
       and created_at < public._business_day_start(public._current_business_date());
end $$;

revoke all on function public._expire_stale_waiting() from public, anon, authenticated;


